"""Copy task3/task4 results into the PRECOMPUTED block of ../verify-prompt1-analysis.js.

Run after editing task3_cassandra-41.json or task4_python-driver.json:
    python .claude/workflows/results/sync_precomputed.py
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
WORKFLOW = HERE.parent / 'verify-prompt1-analysis.js'
BEGIN = '// ==== PRECOMPUTED RESULTS: BEGIN'
END = '// ==== PRECOMPUTED RESULTS: END ===='
SOURCES = [('PRE3', 'task3_cassandra-41.json'), ('PRE4', 'task4_python-driver.json')]


def as_js(name, filename):
    data = json.loads((HERE / filename).read_text(encoding='utf-8'))
    item = lambda x: '    ' + json.dumps(x, ensure_ascii=False) + ','
    return '\n'.join(
        [f'const {name} = {{', '  findings: [']
        + [item(f) for f in data['findings']]
        + ['  ],', '  facts_for_prompt2: [']
        + [item(x) for x in data['facts_for_prompt2']]
        + ['  ],', '}'])


block = '\n'.join(
    [f'{BEGIN} (generated by results/sync_precomputed.py from '
     + ' and '.join(f'results/{f}' for _, f in SOURCES) + '; do not edit by hand) ====']
    + [as_js(name, f) for name, f in SOURCES]
    + [END])
src = WORKFLOW.read_text(encoding='utf-8')
pattern = re.compile(re.escape(BEGIN) + r'.*?' + re.escape(END), re.S)
if len(pattern.findall(src)) != 1:
    raise SystemExit('PRECOMPUTED markers not found exactly once in ' + WORKFLOW.name)
WORKFLOW.write_text(pattern.sub(lambda _: block, src), encoding='utf-8', newline='\n')
print('updated', WORKFLOW.name)
